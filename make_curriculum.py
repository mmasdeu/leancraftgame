#!/usr/bin/env python3
"""Write CURRICULUM.md from the levels themselves.

    python3 make_curriculum.py          rewrites CURRICULUM.md

For each world (a run of consecutive levels with the same "world" in level.json) it lists the
levels with their kind of exercise, the
first paragraph of their lesson, their traps (the statements the player predicts, or the
questions of a reading level) and their number of tests. Run it after changing a level.
"""
import re
import sys
from itertools import groupby
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT / "web"))
import server  # noqa: E402

HEAD = """# Curriculum (v3)

Lean Craft Game v3 is a story in thirteen worlds (see [NARRATIVE.md](NARRATIVE.md)): the player
joins the Annex, a team that keeps a Lean library beside an AI prover. The player never writes
a proof: the player **writes** a statement or a definition, **reads** Lean and says what it
means, or gives a **witness** or a **counterexample**; the referee does any proving. The way a
level is written is in [AUTHORING.md](AUTHORING.md).

*This file is generated by `python3 make_curriculum.py` from the levels: edit the levels, not
this file.*

Kinds of exercise: **Write** (a definition or a statement), **Read** (questions about Lean
code), **Construct** (a witness, a function, a structure), **Refute** (a counterexample),
**Repair** (fix a colleague's code), **Audit** (does a formal statement say what it claims?).

"""




def first_paragraph(intro):
    """The first paragraph of the lesson after its title, as one line."""
    paras = [p.strip() for p in re.split(r"\n\s*\n", intro) if p.strip()]
    for p in paras:
        if not p.startswith(("#", "```", "|", "*", "-", ">", ":::")):
            return " ".join(p.split())
    return ""


def main():
    levels = [server.load_level(n) for n in server.LEVELS]
    out = [HEAD]
    total = len([lv for lv in levels if lv["world"] != "Final Audit"])
    out.append(f"**{total} levels** in {len({lv['world'] for lv in levels}) - 1} worlds, and a final audit.\n")
    for world, group in groupby(levels, key=lambda lv: lv["world"]):
        group = list(group)
        out.append(f"\n## {world} (levels {group[0]['id']}–{group[-1]['id']})\n" if len(group) > 1
                   else f"\n## {world} (level {group[0]['id']})\n")
        out.append("| # | Level | Kind | Tests |\n|---|---|---|---|")
        for lv in group:
            out.append(f"| {lv['id']} | {lv['title']} | {lv.get('exercise', '')} | {len(lv['tests'])} |")
        out.append("")
        for lv in group:
            out.append(f"**{lv['id']}. {lv['title']}.** {first_paragraph(lv['intro'])}")
            traps = [p["statement"] for p in lv.get("predict", [])] + [q["text"] for q in lv.get("questions", [])]
            if traps:
                out.append("")
                out.append(("Questions: " if lv.get("questions") else "Predictions: ")
                           + "; ".join(t.rstrip(".?") for t in traps) + ".")
            out.append("")
    (ROOT / "CURRICULUM.md").write_text("\n".join(out), encoding="utf-8")
    print(f"Wrote CURRICULUM.md ({len(levels)} levels)")


if __name__ == "__main__":
    main()
